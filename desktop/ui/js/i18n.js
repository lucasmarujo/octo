const current = (() => {
  const chosen = storage.get(LANGUAGE_KEY);
  return LANGUAGES.some((entry) => entry.code === chosen) ? chosen : 'en';
})();

export function language() {
  return current;
}

function fill(template, values) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (Object.hasOwn(values, name) ? String(values[name]) : match));
}

export function translate(code, text, values) {
  const template = code === 'pt-BR' && Object.hasOwn(PT, text) ? PT[text] : text;
  return fill(template, values);
}

export function t(text, values) {
  return translate(current, text, values);
}

export function translateHub(code, text) {
  if (code !== 'pt-BR' || !text) return text;
  for (const [pattern, build] of HUB) {
    const match = text.match(pattern);
    if (match) return build(match);
  }
  return text;
}

export function hubText(text) {
  return translateHub(current, text);
}

export function applyStatic(root = document) {
  document.documentElement.lang = current;
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll('[data-i18n-label]')) node.setAttribute('aria-label', t(node.dataset.i18nLabel));
}

export function setLanguage(code, page) {
  if (code === current) return;
  storage.set(LANGUAGE_KEY, code === 'en' ? null : code);
  if (page) window.sessionStorage.setItem(PAGE_KEY, page);
  window.location.reload();
}

export function pageToReopen() {
  const page = window.sessionStorage.getItem(PAGE_KEY);
  window.sessionStorage.removeItem(PAGE_KEY);
  return page;
}
